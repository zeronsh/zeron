#!/usr/bin/env node
/**
 * Generates edge/src/store/mark-lookalikes.ts: for each letter of the mark's
 * words (docs/plugin-store-data.json `mark_claims.words`), every character
 * that passes for it at a glance, read as the mark rule reads text (NFKC,
 * lowercase, NFKD without nonspacing marks; listing.ts `markText`).
 *
 * The source is Unicode's confusables.txt (UTS #39): every single-character
 * source whose prototype folds to one of those letters, itself folded the
 * same way, kept unless it folds to an ASCII letter (the shared rule reads
 * those already). Added to it, because UTS #39 leaves them out: the Latin
 * letter small capitals (ᴠᴇʀɪꜰɪᴇᴅ), by their Unicode names, and the digit 3
 * for e (0 and 1 are UTS #39's already).
 *
 *   curl -sfLO https://www.unicode.org/Public/security/latest/confusables.txt
 *   node edge/scripts/mark-lookalikes.mjs confusables.txt
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = process.argv[2];
if (!source) throw new Error("usage: node mark-lookalikes.mjs <confusables.txt>");
const text = readFileSync(source, "utf8");
const version = text.match(/^# Version: (.+)$/m)?.[1] ?? "unknown";
const data = JSON.parse(readFileSync(resolve(here, "../../docs/plugin-store-data.json"), "utf8"));
const letters = [...new Set(data.mark_claims.words.join(""))].sort();

const markText = (s) => s.normalize("NFKC").toLowerCase().normalize("NFKD").replace(/\p{Mn}/gu, "");
const fromHex = (field) => String.fromCodePoint(...field.trim().split(/ +/).map((h) => parseInt(h, 16)));

const table = Object.fromEntries(letters.map((l) => [l, new Set()]));
const add = (letter, ch) => {
  const folded = markText(ch);
  if ([...folded].length !== 1 || /[a-z]/.test(folded) || folded === letter) return;
  table[letter]?.add(folded);
};

for (const line of text.split("\n")) {
  const m = line.match(/^([0-9A-F ]+?)\s*;\s*([0-9A-F ]+?)\s*;/);
  if (!m) continue;
  const target = markText(fromHex(m[2]));
  if (target.length === 1 && target in table) add(target, fromHex(m[1]));
}

// LATIN LETTER SMALL CAPITAL A…Z (U+1D00 block and others), which UTS #39
// doesn't list as confusable with the lowercase letters they look like.
const SMALL_CAPITALS = {
  a: 0x1d00, b: 0x0299, c: 0x1d04, d: 0x1d05, e: 0x1d07, f: 0xa730, g: 0x0262, h: 0x029c, i: 0x026a, j: 0x1d0a,
  k: 0x1d0b, l: 0x029f, m: 0x1d0d, n: 0x0274, o: 0x1d0f, p: 0x1d18, q: 0xa7af, r: 0x0280, s: 0xa731, t: 0x1d1b,
  u: 0x1d1c, v: 0x1d20, w: 0x1d21, y: 0x028f, z: 0x1d22
};
for (const [letter, cp] of Object.entries(SMALL_CAPITALS)) add(letter, String.fromCodePoint(cp));
add("e", "3");

const escape = (ch) => {
  const cp = ch.codePointAt(0);
  return cp < 0x7f && /[A-Za-z0-9]/.test(ch) ? ch : `\\u{${cp.toString(16)}}`;
};
const lines = letters.map((l) => `  ${l}: "${[...table[l]].sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).map(escape).join("")}"`);
const out = `/**
 * Generated by edge/scripts/mark-lookalikes.mjs from Unicode confusables.txt
 * (UTS #39, version ${version}), with the Latin small capitals and the digit
 * 3: do not edit. For each letter of the mark's words, the characters that
 * pass for it, as listing.ts \`markText\` folds them.
 */
export const MARK_LOOKALIKES: Readonly<Record<string, string>> = {
${lines.join(",\n")}
};
`;
writeFileSync(resolve(here, "../src/store/mark-lookalikes.ts"), out);
console.log(`mark-lookalikes: ${letters.join("")}, ${Object.values(table).reduce((n, s) => n + s.size, 0)} characters, UTS #39 ${version}`);
