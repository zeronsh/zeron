#!/usr/bin/env python3
"""Writes ui/ds/emoji_data.luau, the emoji picker's catalog (ds/emoji_picker),
from Unicode's emoji-test.txt and CLDR's annotations (English and Chinese
keywords, so a search finds them in either):

  tools/emoji_data.py <emoji-test.txt> <annotations-en.json> <annotations-zh.json>

emoji-test.txt: https://unicode.org/Public/emoji/<version>/emoji-test.txt
annotations: cldr-json's cldr-annotations-full/annotations/<locale>/annotations.json

Each kind is one string (parsed by the picker the first time it opens):
an emoji a line, its fields split by tabs: the emoji, its name, English
keywords, Chinese keywords, and "1" when it takes a skin tone (the five
tones made by putting U+1F3FB..U+1F3FF after its first code point, checked
against the file's own toned forms)."""
import json
import re
import sys
import pathlib

KINDS = [
    ("smileys", "Smileys & Emotion"),
    ("people", "People & Body"),
    ("nature", "Animals & Nature"),
    ("food", "Food & Drink"),
    ("travel", "Travel & Places"),
    ("activities", "Activities"),
    ("objects", "Objects"),
    ("symbols", "Symbols"),
    ("flags", "Flags"),
]
TONES = [0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF]


def toned(emoji: str, tone: int) -> str:
    cps = [ord(c) for c in emoji]
    rest = cps[1:]
    if rest and rest[0] == 0xFE0F:
        rest = rest[1:]
    return "".join(chr(c) for c in [cps[0], tone] + rest)


def main(test_path, en_path, zh_path):
    en = json.load(open(en_path))["annotations"]["annotations"]
    zh = json.load(open(zh_path))["annotations"]["annotations"]
    groups = {}
    order = []
    every = set()
    version = "?"
    group = None
    for line in open(test_path, encoding="utf-8"):
        m = re.match(r"# Version: (\S+)", line)
        if m:
            version = m.group(1)
        m = re.match(r"# group: (.+)", line)
        if m:
            group = m.group(1).strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        m = re.match(r"([0-9A-F ]+?)\s*;\s*(\S+)\s*#\s*(\S+)\s+E[\d.]+\s+(.+)", line)
        if not m:
            continue
        cps, status, emoji, name = m.groups()
        if status != "fully-qualified":
            continue
        every.add(emoji)
        if group == "Component":
            continue
        # A toned form is the base's, chosen by the picker's tone.
        if any(0x1F3FB <= ord(c) <= 0x1F3FF for c in emoji):
            continue
        groups.setdefault(group, []).append((emoji, name.strip()))
        order.append(emoji)

    def words(table, emoji):
        a = table.get(emoji) or table.get(emoji.replace("️", ""))
        if not a:
            return ""
        return "|".join(w.replace("\t", " ").replace("\n", " ") for w in a.get("default", []))

    out = [
        "-- Generated by tools/emoji_data.py from Unicode's emoji-test.txt",
        f"-- (Emoji {version}) and CLDR's English and Chinese annotations: don't",
        "-- edit. The emoji picker's catalog (ds/emoji_picker): each kind's emoji",
        "-- one a line, fields split by tabs: the emoji, its name, English",
        "-- keywords, Chinese keywords (each `|`-separated), and 1 when it takes",
        "-- a skin tone.",
        "",
        "return {",
        f'\tversion = "{version}",',
        "\tkinds = {",
    ]
    total = 0
    for kid, title in KINDS:
        rows = []
        for emoji, name in groups[title]:
            tone = "1" if all(toned(emoji, t) in every for t in TONES) else ""
            # (Tones only where one modifier after the first code point makes
            # all five: a couple's two people aren't chosen apart here.)
            if tone and len([c for c in emoji if c not in "️‍"]) > 2:
                tone = ""
            rows.append("\t".join([emoji, name, words(en, emoji), words(zh, emoji), tone]))
        total += len(rows)
        body = "\n".join(rows)
        assert "]==]" not in body
        out.append(f'\t\t{{ id = "{kid}", list = [==[{body}]==] }},')
    out += ["\t},", "}", ""]
    path = pathlib.Path(__file__).resolve().parent.parent / "ui" / "ds" / "emoji_data.luau"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"{path}: {total} emoji in {len(KINDS)} kinds")


if __name__ == "__main__":
    main(*sys.argv[1:4])
