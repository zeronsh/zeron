#!/usr/bin/env python3
"""Zeron's colour palette: hues by steps, as Tailwind's, made in OKLCH so
every hue at a step has the same perceived lightness (a 600 weighs the same
in any hue), with a softer chroma than Tailwind's to sit on the glass.

Writes ui/ds/palette.luau. Tune the tables below and run it again:

    python3 tools/palette.py
"""

import math
import os

# Each step's lightness (OKLCH L), and its share of the hue's chroma.
STEPS = [
    ("50", 0.975, 0.10),
    ("100", 0.945, 0.22),
    ("200", 0.895, 0.42),
    ("300", 0.825, 0.66),
    ("400", 0.740, 0.88),
    ("500", 0.655, 1.00),
    ("600", 0.570, 0.98),
    ("700", 0.490, 0.86),
    ("800", 0.410, 0.70),
    ("900", 0.340, 0.56),
    ("950", 0.265, 0.44),
]

# Hues: OKLCH hue angle, peak chroma, and a lightness lift (the warm hues
# read dark and muddy at a cool hue's lightness: yellow's 500 is not an
# olive).
HUES = [
    ("gray", 286, 0.010, 0.00),
    ("red", 25, 0.165, 0.00),
    ("orange", 48, 0.155, 0.02),
    ("amber", 72, 0.150, 0.05),
    ("yellow", 95, 0.145, 0.09),
    ("lime", 128, 0.150, 0.06),
    ("green", 148, 0.145, 0.02),
    ("emerald", 162, 0.135, 0.01),
    ("teal", 182, 0.115, 0.01),
    ("cyan", 208, 0.115, 0.01),
    ("sky", 232, 0.130, 0.00),
    ("blue", 258, 0.165, 0.00),
    ("indigo", 275, 0.165, 0.00),
    ("violet", 292, 0.170, 0.00),
    ("purple", 305, 0.170, 0.00),
    ("fuchsia", 325, 0.170, 0.00),
    ("pink", 350, 0.160, 0.00),
    ("rose", 12, 0.165, 0.00),
]


def to_srgb(L, C, h):
    a = C * math.cos(math.radians(h))
    b = C * math.sin(math.radians(h))
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_**3, m_**3, s_**3
    return (
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
    )


def in_gamut(rgb):
    return all(-1e-4 <= c <= 1 + 1e-4 for c in rgb)


def hex_of(L, C, h):
    # Out of sRGB, chroma gives way (the hue and lightness hold).
    while C > 0 and not in_gamut(to_srgb(L, C, h)):
        C -= 0.002
    def enc(x):
        x = max(0.0, min(1.0, x))
        return round(255 * (12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055))
    r, g, b = to_srgb(L, max(C, 0), h)
    return "#%02x%02x%02x" % (enc(r), enc(g), enc(b))


def main():
    out = [
        "-- Zeron's colour palette: hues by steps (50 to 950), as Tailwind's, in",
        "-- OKLCH: every hue at a step the same perceived lightness, softer than",
        "-- Tailwind's. Generated by tools/palette.py: tune it there, not here.",
        "-- Tokens read it as `$palette.<hue>.<step>`, themes as",
        "-- `{palette.<hue>.<step>}`.",
        "",
        "return {",
    ]
    for name, hue, chroma, lift in HUES:
        cells = []
        for step, L, share in STEPS:
            # The lift fades out toward the ends (50 and 950 stay put).
            t = 1 - abs((L - 0.62) / 0.36)
            cells.append(f'["{step}"] = "{hex_of(min(L + lift * max(t, 0), 0.985), chroma * share, hue)}"')
        out.append(f"\t{name} = {{ {', '.join(cells)} }},")
    out.append("}")
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "ui", "ds", "palette.luau")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(path))


main()
