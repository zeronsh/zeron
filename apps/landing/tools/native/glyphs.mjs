// The hero's words as Geist's own outlines (public/hero/glyphs.js): each
// run shaped as the app shapes it (kerning and the font's default features,
// from apps/zgx/fonts' static Regular and Medium), each glyph a path in font
// units. The page fills them as paths: plain coverage, as the app's CoreText
// masks are, and the same in every browser.
//   node glyphs.mjs
import * as fontkit from "fontkit";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const fonts = fileURLToPath(new URL("../../../zgx/fonts/", import.meta.url));
const out = fileURLToPath(new URL("../../public/hero/glyphs.js", import.meta.url));

export const RUNS = {
  400: ["Search", "No sessions yet", "Ask anything, @ to mention…", "N", "K"],
  500: ["New chat", "Sessions", "Star on GitHub", "Local", "Full access", "MacBook Pro", "hello-world", "No ref", "Opus"],
};
const FILES = { 400: "Geist.ttf", 500: "Geist-Medium.ttf" };

const round = (v) => Math.round(v * 100) / 100;
const data = { upm: 0, glyphs: {}, runs: {} };
for (const [weight, texts] of Object.entries(RUNS)) {
  const font = fontkit.openSync(fonts + FILES[weight]);
  data.upm = font.unitsPerEm;
  for (const text of texts) {
    const run = font.layout(text);
    let x = 0;
    const placed = [];
    run.glyphs.forEach((g, i) => {
      const p = run.positions[i];
      const key = `${weight}:${g.id}`;
      if (!(key in data.glyphs)) {
        data.glyphs[key] = g.path.commands.map((c) => c.command[0] + c.args.map(round).join(" ")).join("")
          .replace(/m/g, "M").replace(/l/g, "L").replace(/q/g, "Q").replace(/b/g, "C").replace(/c/g, "Z");
      }
      placed.push([key, round(x + p.xOffset), round(p.yOffset)]);
      x += p.xAdvance;
    });
    data.runs[`${weight}|${text}`] = { glyphs: placed, advance: round(x) };
  }
}
await writeFile(out, `// Generated by tools/native/glyphs.mjs: Geist's outlines for the hero's words.\nexport default ${JSON.stringify(data)};\n`);
console.log(Object.keys(data.runs).length, "runs,", Object.keys(data.glyphs).length, "glyphs");
