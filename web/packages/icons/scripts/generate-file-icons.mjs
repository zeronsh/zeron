#!/usr/bin/env node
/**
 * Generate the file-type icon bundle for the web client from the desktop's
 * VS Code-derived artwork: `crates/ui/assets/file-icons/` (the tree
 * `rust_embed` embeds) plus the manifest `crates/ui/src/file-icons.json`
 * (the same JSON `file_icons.rs` parses).
 *
 * Two outputs:
 *
 * 1. `web/packages/app/public/file-icons/**` — every SVG copied verbatim,
 *    plus a `dark/` mirror where the seven accent lifts of
 *    `file_icons.rs::dark_icon_svg` are applied ONCE at generate time (the
 *    desktop rewrites lazily in its asset loader; the web has no loader
 *    seam to intercept, so the dark artwork is baked here — a different
 *    path per appearance is what forces the fresh image load on theme
 *    switch).
 * 2. `web/packages/icons/src/generated/file-icons-manifest.ts` — the parsed
 *    manifest, mirroring the `--check` gate pattern of `scripts/generate.mjs`.
 *
 *   node scripts/generate-file-icons.mjs            # write
 *   node scripts/generate-file-icons.mjs --check    # fail when stale
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../../..");
const assetDir = join(repoRoot, "crates/ui/assets/file-icons");
const manifestSource = join(repoRoot, "crates/ui/src/file-icons.json");
const publicDir = join(repoRoot, "web/packages/app/public/file-icons");
const outManifest = join(here, "../src/generated/file-icons-manifest.ts");

/** The desktop's bundle floor (`complete_theme_bundle_is_registered`). */
const MIN_ICON_COUNT = 350;

/** `file_icons.rs::dark_icon_svg` — lift dark accents, case-insensitively. */
const DARK_SUBSTITUTIONS = [
  ["#64748B", "#CBD5E1"],
  ["#71717A", "#D4D4D8"],
  ["#2563EB", "#60A5FA"],
  ["#EA580C", "#FB923C"],
  ["#16A34A", "#4ADE80"],
  ["#8B5CF6", "#A78BFA"],
  ["#A855F7", "#C084FC"],
];

function darkIconSvg(svg) {
  let out = svg;
  for (const [original, brighter] of DARK_SUBSTITUTIONS) {
    out = out.replaceAll(original, brighter).replaceAll(original.toLowerCase(), brighter);
  }
  return out;
}

/** Recursive walk → relative POSIX paths, sorted for deterministic output. */
function walk(dir, prefix = "") {
  const entries = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      entries.push(...walk(join(dir, entry.name), rel));
    } else if (entry.isFile()) {
      entries.push(rel);
    }
  }
  return entries.sort();
}

/**
 * Read an SVG with normalized LF line endings: the source tree is CRLF on
 * Windows checkouts while `web/.gitattributes` pins `eol=lf`, so the copied
 * bytes must be line-ending-stable or the `--check` gate compares CRLF
 * against LF across platforms.
 */
function readSvg(rel) {
  return readFileSync(join(assetDir, rel), "utf8").replaceAll("\r\n", "\n").replaceAll("\r", "\n");
}

const sourceFiles = walk(assetDir).filter((path) => path.endsWith(".svg"));
if (sourceFiles.length < MIN_ICON_COUNT) {
  console.error(`unexpectedly small icon bundle: ${sourceFiles.length}`);
  process.exit(1);
}
for (const rel of sourceFiles) {
  const text = readSvg(rel);
  if (!text.includes("<svg")) {
    console.error(`${rel} is not an svg`);
    process.exit(1);
  }
}

// ── The manifest module ────────────────────────────────────────────────────

// The parsed `Manifest` shape — the fields `file_icons.rs`'s struct reads.
// Unknown JSON keys (`rootFolderNames`, `hidesExplorerArrows`) are dropped
// like serde does; `rootFolder` is kept though the Rust struct lacks it,
// documented-unused (there is no distinct root-folder icon).
const manifest = (({ iconDefinitions, fileExtensions, fileNames, folderNames, languageIds, file, folder, rootFolder }) => ({
  iconDefinitions,
  fileExtensions,
  fileNames,
  folderNames,
  languageIds,
  file: file ?? null,
  folder: folder ?? null,
  rootFolder: rootFolder ?? null,
}))(JSON.parse(readFileSync(manifestSource, "utf8")));
const manifestLines = [
  "// @generated by web/packages/icons/scripts/generate-file-icons.mjs — do not edit.",
  "// Source: crates/ui/src/file-icons.json (the manifest crates/ui/src/file_icons.rs parses).",
  "",
  "export interface FileIconDefinition {",
  "  /** `\"./icons/<asset>.svg\"`, verbatim from the manifest. */",
  "  readonly iconPath: string;",
  "}",
  "",
  "export interface FileIconsManifest {",
  "  readonly iconDefinitions: Readonly<Record<string, FileIconDefinition>>;",
  "  readonly fileExtensions: Readonly<Record<string, string>>;",
  "  readonly fileNames: Readonly<Record<string, string>>;",
  "  readonly folderNames: Readonly<Record<string, string>>;",
  "  readonly languageIds: Readonly<Record<string, string>>;",
  "  readonly file: string | null;",
  "  readonly folder: string | null;",
  "  readonly rootFolder: string | null;",
  "}",
  "",
  "export const fileIconManifest: FileIconsManifest = ",
  JSON.stringify(manifest, null, 2),
  ";",
  "",
];
const manifestContent = manifestLines.join("\n");

// ── The asset trees ────────────────────────────────────────────────────────

/** Write light + dark copies for every source SVG. */
function writeAssets() {
  rmSync(publicDir, { recursive: true, force: true });
  for (const rel of sourceFiles) {
    const text = readSvg(rel);
    const lightPath = join(publicDir, rel);
    mkdirSync(dirname(lightPath), { recursive: true });
    writeFileSync(lightPath, text);
    const darkPath = join(publicDir, "dark", rel);
    mkdirSync(dirname(darkPath), { recursive: true });
    writeFileSync(darkPath, darkIconSvg(text));
  }
}

/** Every file that should exist under `publicDir`, light and dark. */
function expectedPublicFiles() {
  const out = [];
  for (const rel of sourceFiles) {
    out.push(rel);
    out.push(`dark/${rel}`);
  }
  return out.sort();
}

function checkAssets() {
  const expected = expectedPublicFiles();
  const actual = existsSync(publicDir) ? walk(publicDir) : [];
  const expectedSet = new Set(expected);
  const actualSet = new Set(actual);
  const missing = expected.filter((path) => !actualSet.has(path));
  const stale = actual.filter((path) => !expectedSet.has(path));
  if (missing.length > 0 || stale.length > 0) {
    console.error(
      `@zeron/file-icons assets drifted — run \`pnpm --filter @zeron/icons regenerate:file-icons\` and commit the result.`,
    );
    if (missing.length > 0) {
      console.error(`  missing (${missing.length}): ${missing.slice(0, 5).join(", ")}${missing.length > 5 ? " …" : ""}`);
    }
    if (stale.length > 0) {
      console.error(`  stale (${stale.length}): ${stale.slice(0, 5).join(", ")}${stale.length > 5 ? " …" : ""}`);
    }
    return false;
  }
  for (const rel of sourceFiles) {
    const light = readSvg(rel);
    if (readFileSync(join(publicDir, rel), "utf8") !== light) {
      console.error(`  ${rel} drifted from the desktop asset`);
      return false;
    }
    if (readFileSync(join(publicDir, "dark", rel), "utf8") !== darkIconSvg(light)) {
      console.error(`  dark/${rel} no longer matches the dark recolor`);
      return false;
    }
  }
  return true;
}

if (process.argv.includes("--check")) {
  let ok = true;
  const current = existsSync(outManifest) ? readFileSync(outManifest, "utf8") : "";
  if (current !== manifestContent) {
    console.error(
      "file-icons manifest is stale — run `pnpm --filter @zeron/icons regenerate:file-icons` and commit the result.",
    );
    ok = false;
  }
  if (!checkAssets()) {
    ok = false;
  }
  if (ok) {
    console.log(`file-icons bundle is fresh (${sourceFiles.length} icons, ${expectedPublicFiles().length} files).`);
  }
  process.exit(ok ? 0 : 1);
} else {
  writeAssets();
  mkdirSync(dirname(outManifest), { recursive: true });
  writeFileSync(outManifest, manifestContent);
  console.log(
    `wrote ${outManifest} and ${relative(repoRoot, publicDir)} (${sourceFiles.length} icons, ${expectedPublicFiles().length} files)`,
  );
}
