//! macOS Seatbelt: an SBPL profile run through `/usr/bin/sandbox-exec`.
//!
//! Unlike Codex and Claude Code, which confine the *tool commands* their
//! agent runs, Zeron confines the agent CLI itself (its tools and
//! subagents inherit the profile). So the profile keeps Codex's closed-by-
//! default shape but adds what a Node/Bun or Rust CLI needs to run, log in
//! and talk TLS: the Keychain (`SecurityServer`), trust evaluation, DNS
//! configuration. Sources, both Apache-2.0 and both descended from
//! Chromium's sandbox policy:
//!
//! - OpenAI Codex, `codex-rs/sandboxing/src/seatbelt_base_policy.sbpl` and
//!   `seatbelt_network_policy.sbpl` (process, sysctl, pty, device and
//!   platform rules; the fcntl deny; protecting ancestors of carve-outs
//!   against rename).
//! - Anthropic `sandbox-runtime`, `src/sandbox/macos-sandbox-utils.ts`
//!   (mach-lookup and IOKit allow list for Node, loopback rules and why
//!   bind/inbound use `local ip`, string escaping).
//!
//! Rule order matters: Seatbelt applies the *last* matching rule, so the
//! profile goes broad → narrow: allow reads, allow writes to the writable
//! roots, deny writes to read-only carve-outs, deny everything on hidden
//! paths.

use std::path::{Path, PathBuf};

use crate::{Backend, Enforcement, Resolved, SandboxError, SandboxMode};

/// Only ever `/usr/bin/sandbox-exec`, never one found on `PATH`.
pub(crate) const SANDBOX_EXEC: &str = "/usr/bin/sandbox-exec";

pub(crate) fn available() -> bool {
    Path::new(SANDBOX_EXEC).exists()
}

pub(crate) fn enforcement(r: &Resolved) -> Enforcement {
    let mut notes = Vec::new();
    if !r.network {
        notes.push(
            "network off still allows loopback (any port), so the agent reaches Zeron's MCP \
             server and servers it starts itself"
                .into(),
        );
    }
    Enforcement {
        backend: Backend::Seatbelt,
        writes: true,
        hidden: true,
        read_only: true,
        network: true,
        notes,
    }
}

