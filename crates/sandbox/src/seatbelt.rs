    #[test]
    fn base_is_closed_by_default_and_never_opens_launch_services() {
        assert!(BASE.contains("(deny default)"));
        for forbidden in [
            "(allow lsopen",
            "(allow appleevent-send",
            "\"com.apple.coreservices.launchservicesd\"",
            "\"com.apple.coreservices.appleevents\"",
            "(allow file-write*)",
            "(allow network",
            "(allow default",
        ] {
            assert!(!BASE.contains(forbidden), "base profile allows {forbidden}");
        }
    }

    #[test]
    fn strings_escape_quotes_and_backslashes() {
        assert_eq!(string(Path::new("/a b/c")).unwrap(), r#""/a b/c""#);
        assert_eq!(
            string(Path::new(r#"/we"ird\dir"#)).unwrap(),
            r#""/we\"ird\\dir""#
        );
        assert_eq!(string(Path::new("/ünï/ç😀")).unwrap(), "\"/ünï/ç😀\"");
        assert!(matches!(
            string(Path::new("/new\nline")),
            Err(SandboxError::UnsupportedPath(_))
        ));
        // A path that tries to close the string and inject a rule stays one
        // literal.
        assert_eq!(
            string(Path::new(r#"/x") (allow default) ("#)).unwrap(),
            r#""/x\") (allow default) (""#
        );
    }
