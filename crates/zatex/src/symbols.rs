/// Delimiter names usable after `\left`, `\right`, `\big`, …; `None` is the
/// null delimiter `.`.
pub(crate) fn delimiter_command(name: &str) -> Option<Option<char>> {
    Some(Some(match name {
        "{" | "lbrace" => '{',
        "}" | "rbrace" => '}',
        "|" | "Vert" | "lVert" | "rVert" => '‖',
        "vert" | "lvert" | "rvert" | "mid" => '|',
        "langle" => '⟨',
        "rangle" => '⟩',
        "lfloor" => '⌊',
        "rfloor" => '⌋',
        "lceil" => '⌈',
        "rceil" => '⌉',
        "lbrack" => '[',
        "rbrack" => ']',
        "lgroup" => '⟮',
        "rgroup" => '⟯',
        "backslash" => '\\',
        "uparrow" => '↑',
        "downarrow" => '↓',
        "updownarrow" => '↕',
        "Uparrow" => '⇑',
        "Downarrow" => '⇓',
        "Updownarrow" => '⇕',
        _ => return None,
    }))
}

pub(crate) fn delimiter_char(ch: char) -> Option<Option<char>> {
    Some(match ch {
        '.' => None,
        '(' | ')' | '[' | ']' | '|' | '/' => Some(ch),
        '<' => Some('⟨'),
        '>' => Some('⟩'),
        '⟨' | '⟩' | '⌊' | '⌋' | '⌈' | '⌉' | '‖' | '{' | '}' => Some(ch),
        _ => return None,
    })
}

/// Class of a literal character typed in math mode.
pub(crate) fn char_class(ch: char) -> (char, Class) {
    use Class::*;
    match ch {
        '+' => ('+', Bin),
        '-' | '−' => ('−', Bin),
        '*' => ('∗', Bin),
        '=' | '<' | '>' | ':' => (ch, Rel),
        ',' | ';' => (ch, Punct),
        '(' | '[' => (ch, Open),
        ')' | ']' | '!' | '?' => (ch, Close),
        _ => (ch, reverse_class(ch).unwrap_or(Ord)),
    }
}

/// Unicode math typed directly (`≤`, `→`, `×`): classify like its command.
fn reverse_class(ch: char) -> Option<Class> {
    use Class::*;
    Some(match ch {
        '±' | '∓' | '×' | '÷' | '⋅' | '∘' | '∙' | '∩' | '∪' | '∨' | '∧' | '⊕' | '⊗' | '⊖' | '⊙' => {
            Bin
        }
        '≤' | '≥' | '≠' | '≡' | '≈' | '∼' | '≃' | '≅' | '∝' | '≪' | '≫' | '⊂' | '⊃' | '⊆' | '⊇'
        | '∈' | '∉' | '∋' | '∣' | '∥' | '⊢' | '⊨' | '→' | '←' | '↔' | '⇒' | '⇐' | '⇔' | '⟶'
        | '⟹' | '⟺' | '↦' | '≔' => Rel,
        '⟨' | '⌊' | '⌈' => Open,
        '⟩' | '⌋' | '⌉' => Close,
        _ => return None,
    })
}
